import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { rendered } from './qa-helpers.mjs';
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--ignore-gpu-blocklist','--enable-unsafe-swiftshader']});
const page = await browser.newPage({viewport:{width:1440,height:900}});
page.setDefaultTimeout(30_000);
const errors=[]; page.on('pageerror',e=>errors.push(e.message)); page.on('console',m=>{if(m.type()==='error') errors.push(m.text());});
const checks=[];
try {
 await page.goto('http://127.0.0.1:5173/last-round-defuse/');
 await page.waitForFunction(()=>window.__qa?.view.fp.assets.size===4);
 await page.check('#side-attack');
 await page.click('#play'); await page.waitForFunction(()=>!!document.pointerLockElement);
 await page.evaluate(()=>{const q=window.__qa; q.game.paused=true; q.view.fp.reset();}); await rendered(page);
 await page.screenshot({path:'docs/qa/fps-rifle.png'});
 const framing=await page.evaluate(()=>{const fp=window.__qa.view.fp; fp.root.updateMatrixWorld(true); fp.camera.updateMatrixWorld(true); const v=fp.muzzle.clone().set(0,.074,-.225).applyMatrix4(fp.root.matrixWorld).project(fp.camera); const muzzle=fp.muzzle.clone().applyMatrix4(fp.root.matrixWorld).project(fp.camera); return {receiverTopBelowCrosshairPercent:-v.y*50,muzzle:{x:muzzle.x,y:muzzle.y}};});
 assert.ok(framing.receiverTopBelowCrosshairPercent>=8 && framing.receiverTopBelowCrosshairPercent<=12,JSON.stringify(framing));
 checks.push('rifle receiver top is 8–12% screen height below crosshair; models loaded');
 await page.evaluate(()=>{window.__qa.view.fp.fire();}); await rendered(page);
 assert.equal(await page.evaluate(()=>window.__qa.view.flash.visible),true);
 await page.screenshot({path:'docs/qa/fps-fire.png'});
 await page.evaluate(()=>{const q=window.__qa; q.view.fp.reset(); q.game.player.ammo[0]=9; q.game.reload(q.game.player); q.game.player.reload=1.2;}); await rendered(page);
 assert.ok(await page.evaluate(()=>window.__qa.view.fp.model.getObjectByName('magazine').position.y < -.15));
 await page.screenshot({path:'docs/qa/fps-reload.png'});
 await page.evaluate(()=>{const q=window.__qa;q.game.switch(q.game.player,1);q.view.setWeapon(1);q.view.fp.reset();}); await rendered(page);
 assert.equal(await page.evaluate(()=>window.__qa.game.player.reload),0);
 assert.equal(await page.evaluate(()=>window.__qa.view.fp.model.getObjectByName('magazine').position.y),0);
 await page.screenshot({path:'docs/qa/fps-pistol.png'});
 await page.evaluate(()=>{const q=window.__qa;q.game.switch(q.game.player,0);q.view.setWeapon(0);q.view.fp.reset();}); await rendered(page);
 assert.equal(await page.evaluate(()=>window.__qa.view.fp.model.getObjectByName('magazine').position.y),0);
 checks.push('muzzle flash, recoil, visible magazine removal, interrupted reload and cached rifle re-entry');
 await page.evaluate(()=>{const q=window.__qa; const g=q.game; g.player.action='plant'; g.player.progress=1; q.view.fp.select(3); q.view.fp.reset();}); await rendered(page);
 await page.screenshot({path:'docs/qa/fps-c4.png'});
 assert.equal(await page.evaluate(()=>window.__qa.view.fp.active),3);
 await page.evaluate(()=>{const q=window.__qa; q.game.cancel(q.game.player);q.game.bomb={x:q.game.player.x,z:q.game.player.z-1,site:'A',timer:40};q.setPitch(-.7);q.view.fp.select(0);q.view.fp.reset();}); await rendered(page);
 assert.equal(await page.evaluate(()=>window.__qa.view.bomb.children.length),1);
 await page.screenshot({path:'docs/qa/world-c4.png'});
 await page.evaluate(()=>{const q=window.__qa;q.game.resetRound();q.view.reset(q.game);q.setPitch(0);}); await rendered(page);
 assert.equal(await page.evaluate(()=>window.__qa.view.fp.motion.recoil),0);
 assert.equal(await page.evaluate(()=>window.__qa.view.fp.motion.switchRemaining),0);
 assert.equal(await page.evaluate(()=>window.__qa.view.fp.model.getObjectByName('magazine').position.y),0);
 checks.push('C4 while planting, planted world model, round reset clears all motion');
 await page.evaluate(()=>{const g=window.__qa.game;g.paused=false;g.bomb={x:0,z:0,site:'A',timer:40};for(const a of g.actors.filter(a=>g.side(a.team)==='defend'))g.damage(a,g.player,100);});
 await page.waitForFunction(()=>document.querySelector('#round-result').textContent.includes('全灭'));
 assert.deepEqual(await page.evaluate(()=>window.__qa.game.result),{side:'attack',reason:'elimination'});
 checks.push('planted defenders eliminated immediately shows attack elimination win');
 assert.deepEqual(errors,[]);
 await writeFile('docs/qa/weapon-qa.json',JSON.stringify({testedAt:new Date().toISOString(),checks,framing,errors},null,2));console.log({checks,framing,errors});
} finally { await browser.close(); }
