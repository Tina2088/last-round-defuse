import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { frozenClock } from './qa-helpers.mjs';

const url = process.env.QA_URL ?? 'https://tina2088.github.io/last-round-defuse/';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--enable-webgl', '--ignore-gpu-blocklist', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.setDefaultTimeout(30_000);
const errors = []; const warnings = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); if (message.type() === 'warning') warnings.push(message.text()); });
page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
try {
  const response = await page.goto(url);
  assert.equal(response.status(), 200); await page.waitForSelector('#play');
  assert.equal(await page.locator('#brand small').innerText(), 'v0.1.2.2');
  assert.match(await page.title(), /v0\.1\.2\.2$/);
  assert.equal(await page.evaluate(() => typeof window.__LRD__), 'undefined');
  assert.equal(await page.isChecked('#one-shot'), true);
  await page.uncheck('#one-shot');
  assert.equal(await page.locator('#side-defend').isChecked(), true);
  await page.check('#side-attack'); await page.click('#language');
  assert.equal(await page.isChecked('#one-shot'), false);
  assert.match(await page.locator('.one-shot-setting').innerText(), /One-shot kill/);
  assert.equal(await page.locator('#side-attack').isChecked(), true);
  assert.match(await page.locator('.side-picker').innerText(), /Starting side/);
  await page.click('#language'); await page.check('#side-defend');
  assert.match(await page.locator('#menu').innerText(), /守方全灭则攻方立即获胜/);
  await page.waitForFunction(() => performance.getEntriesByType('resource').filter(e => /models\/(rifle_fp|pistol|c4)\.glb/.test(e.name) && e.responseEnd > 0).length === 3);
  const transfer = await page.evaluate(() => {
    const entries = [...performance.getEntriesByType('navigation'), ...performance.getEntriesByType('resource')].filter(e => e.name.startsWith(location.origin));
    const files = entries.map(e => ({url:e.name,transferBytes:e.transferSize,encodedBytes:e.encodedBodySize,decodedBytes:e.decodedBodySize}));
    return {files,transferBytes:files.reduce((n,e)=>n+e.transferBytes,0),encodedBytes:files.reduce((n,e)=>n+e.encodedBytes,0),decodedBytes:files.reduce((n,e)=>n+e.decodedBytes,0)};
  });
  await writeFile('docs/qa/public-first-load.json',JSON.stringify({testedAt:new Date().toISOString(),method:'Fresh Chrome browser context, empty HTTP cache, Resource Timing + Navigation Timing; response headers included in transferBytes',...transfer},null,2));
  assert.equal(await page.evaluate(() => typeof window.__qa), 'undefined');
  await page.screenshot({ path: 'test-results/public-start.png' });
  await page.selectOption('#size', '3'); await page.selectOption('#difficulty', 'easy');
  await page.click('#play'); await page.waitForFunction(() => !!document.pointerLockElement);
  await page.waitForFunction(() => document.getElementById('our-side').className === 'defend');
  await page.keyboard.press('KeyL');
  await page.waitForFunction(() => document.getElementById('weapon').textContent.includes('Rifle'));
  assert.equal(await page.evaluate(() => !!document.pointerLockElement), true);
  assert.equal(await page.locator('#hud-language').innerText(), '中文 · L');
  await page.keyboard.press('KeyL');
  await page.waitForFunction(() => document.getElementById('weapon').textContent.includes('步枪'));
  await page.waitForFunction(() => document.getElementById('clock-label').textContent === '回合时限 · 105 秒'); assert.equal(await page.locator('#weapon b').innerText(), '30 / 90');
  await page.mouse.down(); await page.waitForFunction(() => document.querySelector('#weapon b').textContent !== '30 / 90'); await page.mouse.up();
  assert.notEqual(await page.locator('#weapon b').innerText(), '30 / 90');
  await page.keyboard.press('Digit2'); await page.waitForFunction(() => document.querySelector('#weapon small').textContent.includes('手枪')); assert.match(await page.locator('#weapon small').innerText(), /手枪/);
  await page.keyboard.press('Digit3'); await page.waitForFunction(() => document.querySelector('#weapon small').textContent.includes('刀')); assert.match(await page.locator('#weapon small').innerText(), /刀/);
  await page.keyboard.press('Digit1'); await page.waitForFunction(() => document.querySelector('#weapon small').textContent.includes('步枪'));
  const distanceBefore = await page.locator('#site-arrows').innerText();
  await page.keyboard.down('KeyW'); await page.waitForFunction(before => document.getElementById('site-arrows').innerText !== before, distanceBefore); await page.keyboard.up('KeyW');
  await page.screenshot({ path: 'test-results/public-gameplay.png' });
  await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.pointerLockElement);
  assert.match(await page.locator('h1').innerText(), /作战暂停/);
  assert.equal(await page.isChecked('#one-shot'), false);
  await page.check('#one-shot');
  await frozenClock(page);
  await page.click('#language'); assert.equal(await page.locator('h1').innerText(), 'Operation paused');
  assert.equal(await page.isChecked('#one-shot'), true);
  await page.waitForFunction(() => document.getElementById('weapon').textContent.includes('Rifle'));
  await page.waitForFunction(() => document.getElementById('clock-label').textContent === 'Round limit · 105 seconds');
  await page.screenshot({ path: 'test-results/public-pause-en.png' });
  await page.reload(); await page.waitForSelector('#play');
  assert.equal(await page.isChecked('#one-shot'), true);
  await page.check('#side-attack'); await page.click('#play');
  await page.waitForFunction(() => !!document.pointerLockElement && document.getElementById('our-side').className === 'attack');
  await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.pointerLockElement);
  // Verify the production opt-in API, including live getters after replacing the match.
  const qaUrl = new URL(url); qaUrl.searchParams.set('qa', '0');
  await page.goto(qaUrl.href); await page.waitForSelector('#play');
  assert.equal(await page.evaluate(() => typeof window.__LRD__), 'undefined');
  qaUrl.searchParams.set('qa', '1');
  await page.goto(qaUrl.href); await page.waitForSelector('#play');
  assert.equal(await page.evaluate(() => typeof window.__qa), 'undefined');
  assert.deepEqual(await page.evaluate(() => ({version: window.__LRD__.version, oneShotKill: window.__LRD__.oneShotKill,
    keys: Object.keys(window.__LRD__).sort(), actorKeys: Object.keys(window.__LRD__.actors()[0]).sort()})),
    {version: 'v0.1.2.2', oneShotKill: true, keys: ['actors', 'oneShotKill', 'version'], actorKeys: ['hp', 'id', 'team', 'x', 'z']});
  assert.equal(await page.evaluate(() => { window.__LRD__.actors()[0].hp = -1; return window.__LRD__.actors()[0].hp; }), 100);
  await page.uncheck('#one-shot'); await page.selectOption('#size', '3'); await page.selectOption('#difficulty', 'easy');
  await page.click('#play'); await page.waitForFunction(() => !!document.pointerLockElement);
  await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.pointerLockElement);
  assert.equal(await page.evaluate(() => window.__LRD__.oneShotKill), false);
  assert.deepEqual(await page.evaluate(() => window.__LRD__.actors().map(a => a.hp)), [100, 80, 80, 80, 80, 80]);
  await page.check('#one-shot'); await page.click('#restart'); await page.waitForFunction(() => !!document.pointerLockElement);
  await page.keyboard.press('Escape'); await page.waitForFunction(() => !document.pointerLockElement);
  assert.equal(await page.evaluate(() => window.__LRD__.oneShotKill), true);
  assert.equal(await page.evaluate(() => window.__LRD__.actors().length), 6);
  assert.deepEqual(errors, []);
  assert.deepEqual(warnings.filter(w => /PCFSoftShadowMap|deprecated|removed/i.test(w)), []);
  const result = { url, status: response.status(), testedAt: new Date().toISOString(), version: await page.locator('#brand small').innerText(), checks: ['v0.1.2.2 deployed', 'one-shot defaults ON and fresh page resets to ON', 'start OFF retained through language switch and into pause', 'pause toggle ON retained through language switch', 'default defend and bilingual side choice retained', 'both defend and attack starts show correct HUD side', 'rule 9 visible', 'all three GLBs loaded from Pages', 'production WebGL render', 'no development state hook', 'real pointer lock', '3v3 start', 'fire and weapon switch', 'move', 'Escape and frozen clock', 'Chinese/English', 'live language shortcut retains pointer lock', 'localized round duration', 'no deprecated shadow API warnings'], errors, warnings };
  await writeFile('test-results/public-smoke.json', JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
